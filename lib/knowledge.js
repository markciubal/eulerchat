/** The fields — the layer above what people join. */
export const fields = Object.keys(knowledge).filter(
  (name) => knowledge[Object.keys(knowledge).find((k) => k === name)] !== undefined,
);

/** Subjects with nothing beneath them: the narrowest rooms there are. */
export function subfields(parents = knowledge) {
  const hasChildren = new Set(Object.values(parents));
  return Object.keys(parents).filter((name) => !hasChildren.has(name)).sort();
}

/**
 * What sits directly under each name, sorted, with the divisions under
 * `knowledge`. Built once: the catalogue is browsed a level at a time, and
 * walking eleven hundred entries for every level would be the whole cost of
 * doing so.
 */
export function childrenOf(parents = knowledge) {
  const under = new Map();
  for (const [child, parent] of Object.entries(parents)) {
    if (!under.has(parent)) under.set(parent, []);
    under.get(parent).push(child);
  }
  for (const kids of under.values()) kids.sort();
  return under;
}
