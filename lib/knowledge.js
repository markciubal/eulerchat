/**
 * What people are interested in, and where each interest sits.
 *
 * Layers: a dozen broad divisions, the fields within them, and beneath those
 * the interests themselves — and it is mostly the interests that are the
 * rooms. Somebody joins `entomology`, not `biology`; the field above it is
 * there to say where entomology *is*, so that it sits near mycology and
 * nowhere near topology before a single person has joined either.
 *
 * It started as fields of study, because academic divisions are the one
 * taxonomy of subjects that people already share. A catalogue of interests is
 * not a university prospectus, though, and most of what anybody wants to talk
 * about is not on one: the match at the weekend, the dog, the rent, the thing
 * they are building in the shed. So it was filled in three passes, and each
 * pass is a different reason for somebody to stay:
 *
 * - **The obvious.** What anybody would look for first — football, cooking,
 *   dogs, television, parenting, personal finance. If these are missing the
 *   place looks empty however much else is here.
 * - **The niche.** Fountain pens, lockpicking, narrowboats, roguelikes. These
 *   are the rooms people cannot find elsewhere, and the ones that keep them.
 * - **The modern.** Large language models, pickleball, heat pumps, the
 *   fediverse. A catalogue without them reads as one nobody has looked at in
 *   ten years.
 *
 * A fourth layer exists where an interest is big enough to have interests of
 * its own: `photography` holds `film photography`, `video games` holds
 * `roguelikes`. Every name here is a room somebody can join, whatever layer it
 * is on; the layers say what is near what, what a join can widen into, and how
 * the catalogue is browsed. Anything it has never heard of still works, it
 * simply goes unanchored.
 *
 * Every entry is `child: parent`, an edge list rather than nested objects:
 * easier to extend by hand, and exactly the shape a tool baking one out of
 * Wikipedia would produce. A name is lowercase letters, digits, spaces and
 * hyphens, thirty-one characters at most, because that is what the server
 * accepts as a subject; `test/catalogue.test.js` holds every entry to it, and
 * catches a name written twice, which an object literal would swallow.
 */
